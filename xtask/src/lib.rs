pub mod cocogitto;
use cocogitto::{Commit, Generated};
use semver::Version;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::{fs, path::Path, process::Command};
use toml_edit::{DocumentMut, value};

pub type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;
pub const GENERATOR: &str = cocogitto::GENERATOR;
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct State {
    pub source_head: String,
    pub version: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub generator: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub notes_sha256: Option<String>,
}
fn digest(notes: &str) -> String {
    Sha256::digest(notes.as_bytes())
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}
/// Parse/classify/bump with the package. Validation never renders fresh release prose.
fn packaged_release(
    published: &Version,
    commits: Vec<Commit>,
) -> Result<Option<(Version, Generated)>> {
    let generated = cocogitto::generate(&published.to_string(), commits, 0, None)?;
    let Some(version) = generated.releases[0].version.as_deref() else {
        return Ok(None);
    };
    Ok(Some((Version::parse(version)?, generated)))
}
/// Render only during preparation/examples, never during publication.
pub fn generated_release(
    published: &Version,
    commits: Vec<Commit>,
) -> Result<Option<(Version, String)>> {
    let timestamp = commits
        .iter()
        .map(|c| c.author.timestamp)
        .max()
        .unwrap_or(0);
    let generated = cocogitto::generate(&published.to_string(), commits, timestamp, None)?;
    let Some(version) = generated.releases[0].version.as_deref() else {
        return Ok(None);
    };
    let version = Version::parse(version)?;
    release_notes(&generated.markdown, &version)?;
    Ok(Some((version, generated.markdown)))
}

#[derive(Debug)]
pub struct Plan {
    pub version: Version,
    pub changelog: String,
    pub notes: String,
    pub state: State,
}
/// Integrate one package-generated section, preserving every published byte.
pub fn plan(
    published: &Version,
    current: &Version,
    changelog: &str,
    source_head: &str,
    commits: Vec<Commit>,
) -> Result<Option<Plan>> {
    if current < published {
        return Err("Manifest version decreased below the published release".into());
    }
    let Some((version, notes)) = generated_release(published, commits)? else {
        return Ok(None);
    };
    if version < *current {
        return Err(
            "Manifest exceeds the package-calculated version; review pending metadata".into(),
        );
    }
    let parts = sections(changelog);
    let at = parts.first().map_or(changelog.len(), |p| p.1);
    let end = if current > published {
        if parts.first().map(|p| &p.0) != Some(current) {
            return Err("Pending manifest/changelog mismatch".into());
        }
        parts.get(1).map_or_else(
            || {
                changelog
                    .find("Changelog generated by")
                    .unwrap_or(changelog.len())
            },
            |p| p.1,
        )
    } else {
        at
    };
    let updated = format!(
        "{}{}\n- - -\n\n{}",
        &changelog[..at],
        notes,
        &changelog[end..]
    );
    let state = State {
        source_head: source_head.into(),
        version: version.to_string(),
        generator: Some(GENERATOR.into()),
        notes_sha256: Some(digest(&notes)),
    };
    Ok(Some(Plan {
        version,
        notes,
        changelog: updated,
        state,
    }))
}
fn private_or_placeholder(text: &str) -> bool {
    let lower = text.to_ascii_lowercase();
    let words: Vec<_> = lower
        .split(|c: char| !c.is_alphanumeric())
        .filter(|w| !w.is_empty())
        .collect();
    words.iter().any(|w| {
        matches!(
            *w,
            "todo" | "tbd" | "placeholder" | "unreleased" | "cycle" | "milestone"
        )
    }) || words.windows(2).any(|pair| {
        matches!(pair[0], "m" | "k" | "l" | "r" | "inf" | "kf" | "wp" | "if")
            && pair[1].chars().all(|c| c.is_ascii_digit())
    }) || words.iter().any(|w| {
        let (prefix, number) = w.split_at(w.find(|c: char| c.is_ascii_digit()).unwrap_or(w.len()));
        !number.is_empty()
            && number.chars().all(|c| c.is_ascii_digit())
            && matches!(prefix, "m" | "k" | "l" | "r" | "inf" | "kf" | "wp" | "if")
    }) || lower.contains("ci(release):")
        || lower.contains("update version")
        || lower.contains("bump version")
        || lower.contains("version bump")
        || lower.contains("coming soon")
}

fn sections(changelog: &str) -> Vec<(Version, usize, usize)> {
    let mut offset = 0;
    let mut result = Vec::new();
    for line in changelog.split_inclusive('\n') {
        if let Some(title) = line.trim_end().strip_prefix("## ")
            && let Ok(version) = Version::parse(if let Some(bracketed) = title.strip_prefix('[') {
                bracketed
                    .split(']')
                    .next()
                    .unwrap_or("")
                    .trim_start_matches('v')
            } else {
                title
                    .split_whitespace()
                    .next()
                    .unwrap_or("")
                    .trim_start_matches('v')
            })
        {
            result.push((version, offset, offset + line.len()));
        }
        offset += line.len();
    }
    result
}

pub fn release_notes(changelog: &str, version: &Version) -> Result<String> {
    // Git can check out CRLF on Windows; release prose must compare identically
    // with the LF body published by the Linux preparation/publication jobs.
    let normalized = changelog.replace("\r\n", "\n");
    let changelog = normalized.as_str();
    let parts = sections(changelog);
    if parts.first().map(|p| &p.0) != Some(version)
        || parts.iter().filter(|p| &p.0 == version).count() != 1
    {
        return Err(
            format!("First CHANGELOG version section must uniquely match {version}").into(),
        );
    }
    let end = parts.get(1).map_or(changelog.len(), |p| p.1);
    let section = changelog[parts[0].1..end]
        .split("Changelog generated by")
        .next()
        .unwrap()
        .trim_end()
        .trim_end_matches("- - -")
        .trim_end();
    let notes = section.split_once('\n').map_or("", |(_, body)| body).trim();
    let substantive = notes
        .lines()
        .any(|l| l.trim_start().starts_with("- ") && l.trim().len() > 2);
    if !substantive || private_or_placeholder(notes) {
        return Err(format!(
            "CHANGELOG {version} has empty, placeholder or internal planning notes"
        )
        .into());
    }
    Ok(format!("{}\n", section))
}

pub fn git(root: &Path, args: &[&str]) -> Result<String> {
    let out = Command::new("git").current_dir(root).args(args).output()?;
    if !out.status.success() {
        return Err(format!(
            "git {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr)
        )
        .into());
    }
    Ok(String::from_utf8(out.stdout)?)
}

pub fn version(root: &Path) -> Result<Version> {
    let cargo = fs::read_to_string(root.join("Cargo.toml"))?.parse::<DocumentMut>()?;
    Ok(Version::parse(
        cargo["package"]["version"]
            .as_str()
            .ok_or("Missing Cargo package version")?,
    )?)
}

/// Only changes release-owned files. Does not stage, commit, push or invoke Git mutations.
pub fn apply(root: &Path, plan: &Plan) -> Result<()> {
    let mut cargo = fs::read_to_string(root.join("Cargo.toml"))?.parse::<DocumentMut>()?;
    cargo["package"]["version"] = value(plan.version.to_string());
    let mut lock = fs::read_to_string(root.join("Cargo.lock"))?.parse::<DocumentMut>()?;
    let packages = lock["package"]
        .as_array_of_tables_mut()
        .ok_or("Cargo.lock package list missing")?;
    let package_lock = packages
        .iter_mut()
        .find(|p| p["name"].as_str() == Some("rune-infer"))
        .ok_or("Cargo.lock Infer package missing")?;
    package_lock["version"] = value(plan.version.to_string());
    fs::write(root.join("Cargo.toml"), cargo.to_string())?;
    fs::write(root.join("Cargo.lock"), lock.to_string())?;
    fs::write(root.join("CHANGELOG.md"), &plan.changelog)?;
    fs::create_dir_all(root.join(".release"))?;
    fs::write(
        root.join(".release/prepared.json"),
        format!("{}\n", serde_json::to_string_pretty(&plan.state)?),
    )?;
    Ok(())
}

pub fn validate_manifests(root: &Path) -> Result<()> {
    let version = version(root)?.to_string();
    let cargo = fs::read_to_string(root.join("Cargo.toml"))?.parse::<DocumentMut>()?;
    let lock = fs::read_to_string(root.join("Cargo.lock"))?.parse::<DocumentMut>()?;
    if cargo["package"]["version"].as_str() != Some(&version)
        || !lock["package"]
            .as_array_of_tables()
            .ok_or("Missing lock packages")?
            .iter()
            .any(|p| {
                p["name"].as_str() == Some("rune-infer") && p["version"].as_str() == Some(&version)
            })
    {
        return Err("Cargo.toml and Cargo.lock versions must agree".into());
    }
    Ok(())
}

pub fn validate_versions(root: &Path) -> Result<()> {
    validate_manifests(root)?;
    release_notes(
        &fs::read_to_string(root.join("CHANGELOG.md"))?,
        &version(root)?,
    )?;
    Ok(())
}

pub fn validate_event(root: &Path, event: &serde_json::Value) -> Result<()> {
    validate_versions(root)?;
    let version = version(root)?;
    let notes = release_notes(&fs::read_to_string(root.join("CHANGELOG.md"))?, &version)?;
    if event["release"]["tag_name"] != format!("v{version}")
        || event["release"]["body"].as_str().map(str::trim) != Some(notes.trim())
    {
        return Err("Published version/body does not match the prepared CHANGELOG section".into());
    }
    Ok(())
}

pub fn published_version(root: &Path) -> Result<Version> {
    git(root, &["tag", "--list", "v*"])?
        .lines()
        .filter_map(|tag| Version::parse(tag.strip_prefix('v')?).ok())
        .filter(|v| v.pre.is_empty())
        .max()
        .ok_or("No release tags found; fetch full history/tags".into())
}
fn state(root: &Path) -> Result<Option<State>> {
    let path = root.join(".release/prepared.json");
    if path.exists() {
        Ok(Some(serde_json::from_slice(&fs::read(path)?)?))
    } else {
        Ok(None)
    }
}
fn valid_state(state: &State) -> Result<()> {
    Version::parse(&state.version)?;
    if state.source_head.len() != 40 || !state.source_head.chars().all(|c| c.is_ascii_hexdigit()) {
        return Err("Invalid prepared source revision".into());
    }
    if state.generator.as_deref().is_some_and(|g| g != GENERATOR)
        || state.generator.is_some() != state.notes_sha256.is_some()
    {
        return Err("Unsupported or incomplete prepared generator metadata".into());
    }
    Ok(())
}
pub fn history_base(
    published: &Version,
    current: &Version,
    state: Option<&State>,
) -> Result<String> {
    if let Some(state) = state {
        valid_state(state)?;
        if Version::parse(&state.version)? > *published {
            if state.version != current.to_string() {
                return Err("Invalid pending release state".into());
            }
            return Ok(state.source_head.clone());
        }
    }
    Ok(format!("v{published}"))
}
fn source_commits(root: &Path, base: &str) -> Result<Vec<Commit>> {
    let history = git(
        root,
        &[
            "log",
            "--no-merges",
            "--reverse",
            "--format=%H%x00%an%x00%B%x00%ct%x00",
            &format!("{base}..HEAD"),
        ],
    )?;
    let fields: Vec<_> = history.split('\0').collect();
    Ok(fields
        .chunks(4)
        .filter(|f| f.len() == 4)
        .map(|f| {
            let mut commit = Commit::new(f[0].trim().into(), f[2].trim().into());
            commit.author.name = Some(f[1].trim().into());
            commit.author.timestamp = f[3].trim().parse().unwrap_or(0);
            commit
        })
        .collect())
}
pub fn repository_plan(root: &Path) -> Result<Option<Plan>> {
    validate_manifests(root)?;
    let published = published_version(root)?;
    let current = version(root)?;
    if current < published {
        return Err("Manifest version decreased below the published release".into());
    }
    let state = state(root)?;
    let base = history_base(&published, &current, state.as_ref())?;
    if base.starts_with('v') {
        git(root, &["merge-base", &base, "HEAD"])?;
    } else {
        git(root, &["merge-base", "--is-ancestor", &base, "HEAD"])?;
    }
    // Consumed metadata prevents bookkeeping merge loops; full pending history
    // still determines the greatest package bump and the complete release prose.
    if packaged_release(&published, source_commits(root, &base)?)?.is_none() {
        return Ok(None);
    }
    plan(
        &published,
        &current,
        &fs::read_to_string(root.join("CHANGELOG.md"))?,
        git(root, &["rev-parse", "HEAD"])?.trim(),
        source_commits(root, &format!("v{published}"))?,
    )
}
/// No subject/parent-count gate: every main push gets a validated decision.
pub fn pending_release(
    current: &Version,
    published: &Version,
    state: Option<&State>,
) -> Result<bool> {
    if current < published {
        return Err("Manifest version decreased below the published release".into());
    }
    if let Some(state) = state {
        valid_state(state)?;
        if Version::parse(&state.version)? > *current {
            return Err("Prepared metadata is newer than the manifest".into());
        }
    }
    if current == published {
        return Ok(false);
    }
    let state = state.ok_or("Unpublished manifest version has no prepared release metadata")?;
    if state.version != current.to_string() {
        return Err("Pending version and prepared metadata disagree".into());
    }
    Ok(true)
}
pub fn validate_promotion(root: &Path) -> Result<bool> {
    validate_manifests(root)?;
    let current = version(root)?;
    let published = published_version(root)?;
    let state = state(root)?;
    if !pending_release(&current, &published, state.as_ref())? {
        return Ok(false);
    }
    let state = state.unwrap();
    git(
        root,
        &["merge-base", "--is-ancestor", &state.source_head, "HEAD"],
    )?;
    validate_versions(root)?;
    let notes = release_notes(&fs::read_to_string(root.join("CHANGELOG.md"))?, &current)?;
    validate_note_receipt(&state, &notes)?;
    if packaged_release(&published, source_commits(root, &state.source_head)?)?.is_some() {
        return Err(
            "Unprepared development followed the consumed source; prepare and review again".into(),
        );
    }
    let (calculated, _) =
        packaged_release(&published, source_commits(root, &format!("v{published}"))?)?
            .ok_or("Prepared version has no releasable reviewed source history")?;
    if calculated != current {
        return Err("Prepared manifest does not match the Cocogitto-calculated version".into());
    }
    Ok(true)
}

/// Verify the immutable prepared-note receipt without regenerating its prose.
pub fn validate_note_receipt(state: &State, notes: &str) -> Result<()> {
    valid_state(state)?;
    if state
        .notes_sha256
        .as_ref()
        .is_some_and(|hash| *hash != digest(notes))
    {
        return Err("Prepared release notes changed after preparation".into());
    }
    Ok(())
}

/// Release PR merges have already been tested in preparation. Only skip their
/// generated metadata: dependency/source changes must still receive normal CI.
pub fn release_metadata_only(
    paths: &[&str],
    before_manifest: &str,
    after_manifest: &str,
    before_lock: &str,
    after_lock: &str,
) -> Result<bool> {
    if !paths.contains(&".release/prepared.json")
        || paths.iter().any(|p| {
            !matches!(
                *p,
                "Cargo.toml" | "Cargo.lock" | "CHANGELOG.md" | ".release/prepared.json"
            )
        })
    {
        return Ok(false);
    }
    fn normalized(text: &str, lock: bool) -> Result<String> {
        let mut doc = text.replace("\r\n", "\n").parse::<DocumentMut>()?;
        if lock {
            for package in doc["package"]
                .as_array_of_tables_mut()
                .ok_or("Missing lock packages")?
                .iter_mut()
            {
                if package["name"].as_str() == Some("rune-infer") {
                    package["version"] = value("0.0.0");
                }
            }
        } else {
            doc["package"]["version"] = value("0.0.0");
        }
        Ok(doc.to_string())
    }
    Ok(
        normalized(before_manifest, false)? == normalized(after_manifest, false)?
            && normalized(before_lock, true)? == normalized(after_lock, true)?,
    )
}

pub fn ci_required(root: &Path, before: &str) -> Result<bool> {
    if before.len() != 40
        || !before.chars().all(|c| c.is_ascii_hexdigit())
        || before.chars().all(|c| c == '0')
    {
        return Ok(true);
    }
    let paths = git(root, &["diff", "--name-only", before, "HEAD"])?;
    let paths: Vec<_> = paths.lines().collect();
    if paths.iter().any(|p| {
        !matches!(
            *p,
            "Cargo.toml" | "Cargo.lock" | "CHANGELOG.md" | ".release/prepared.json"
        )
    }) || !paths.contains(&".release/prepared.json")
    {
        return Ok(true);
    }
    let manifest = git(root, &["show", &format!("{before}:Cargo.toml")])?;
    let lock = git(root, &["show", &format!("{before}:Cargo.lock")])?;
    let only_metadata = release_metadata_only(
        &paths,
        &manifest,
        &fs::read_to_string(root.join("Cargo.toml"))?,
        &lock,
        &fs::read_to_string(root.join("Cargo.lock"))?,
    )
    .unwrap_or(false);
    Ok(!(only_metadata && validate_promotion(root).unwrap_or(false)))
}
